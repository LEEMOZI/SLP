from config import LEGAL_SYSTEM_PROMPT


def build_answer_prompt(
    query,
    citations,
    evidence_context=None,
):
    """
    构建最终法律分析 Prompt。

    参数：
        query:
            用户提出的法律问题。

        citations:
            Evidence Pack。
            通常由 build_evidence_pack() 返回。

        evidence_context:
            由 build_evidence_context() 生成的结构化证据上下文。

    返回：
        str:
            提交给 LLM 的最终法律分析 Prompt。

    核心原则：
        Evidence 是本次法律回答的唯一法律依据。
        不允许模型使用自身知识补充 Evidence 中不存在的法律内容。
    """

    if query is None:
        query = ""

    if citations is None:
        citations = []

    if evidence_context is None:
        evidence_context = ""

    # ---------------------------------------------------------
    # 1. 构建 Evidence 引用索引
    # ---------------------------------------------------------

    citation_blocks = []

    for i, citation in enumerate(citations):
        if not isinstance(citation, dict):
            continue

        evidence_id = citation.get(
            "evidence_id",
            f"E{i + 1}",
        )

        citation_type = citation.get(
            "citation_type",
            "",
        )

        category = citation.get(
            "category",
            "",
        )

        role = citation.get(
            "role",
            "",
        )

        law_name = citation.get(
            "law_name",
            "",
        )

        article = citation.get(
            "article",
            "",
        )

        source_document = citation.get(
            "source_document",
            "",
        )

        page = citation.get(
            "page",
            "",
        )

        source = citation.get(
            "source",
            "",
        )

        content = citation.get(
            "content",
            "",
        )

        block = f"""
【引用依据 {i + 1}】

证据编号：
{evidence_id}

引用类型：
{citation_type}

法律分类：
{category}

证据角色：
{role}

法律名称：
{law_name}

条文位置：
{article}

来源文件：
{source_document}

来源：
{source}

页码：
{page}

证据内容：
{content}

---
""".strip()

        citation_blocks.append(block)

    citation_text = "\n\n".join(citation_blocks)

    if not citation_text:
        citation_text = "本次检索没有提供明确的引用依据。"

    # ---------------------------------------------------------
    # 2. Evidence Context
    # ---------------------------------------------------------

    if not evidence_context.strip():
        evidence_context = (
            "本次检索没有提供可用于法律分析的完整证据上下文。"
        )

    # ---------------------------------------------------------
    # 3. 最终 Prompt
    # ---------------------------------------------------------

    prompt = f"""
{LEGAL_SYSTEM_PROMPT}

==================================================
【本次法律分析任务】
==================================================

你需要回答用户提出的法律问题。

最重要的约束：

Evidence 是本次回答的唯一法律依据。

你不得使用模型自身训练知识、一般法律常识、记忆、
推测、经验或者未经本次检索提供的资料补充法律结论。

如果 Evidence 没有明确支持某一法律判断，
必须明确写：

“根据现有检索证据无法确认。”

不得为了让答案看起来完整而自行补充法律规则。

==================================================
【用户问题】
==================================================

{query}

==================================================
【律师引用依据】
==================================================

{citation_text}

==================================================
【完整 Evidence Context】
==================================================

{evidence_context}

==================================================
【Evidence 使用规则】
==================================================

一、Evidence 唯一依据原则

1. 只能依据上述 Evidence 回答。

2. Evidence 中明确出现的内容，可以用于回答。

3. Evidence 中没有出现的内容，不得自行补充。

4. 不得因为模型“知道”某一法律规定，
   就自行加入回答。

5. 不得把模型自身知识伪装成 Evidence。

--------------------------------------------------

二、法律依据类型必须严格区分

请严格区分：

1. 法律规定
2. 司法解释
3. 最高人民法院观点
4. 其他法院裁判观点
5. 指导案例 / 典型案例
6. 学理观点
7. 其他证据或观点

不得将不同类型的法律依据混为一谈。

例如：

Evidence 没有司法解释，
不得自行声称存在相关司法解释。

Evidence 没有最高人民法院观点，
不得自行声称：

“最高人民法院认为……”

Evidence 没有学理观点，
不得自行添加学理观点。

--------------------------------------------------

三、禁止无依据扩展

不得自行增加 Evidence 中没有明确出现的：

- 法律条文
- 法律名称
- 司法解释
- 指导案例
- 典型案例
- 法院观点
- 最高人民法院观点
- 学理观点
- 责任主体
- 责任条件
- 责任范围
- 主观过错
- 因果关系
- 举证责任
- 免责事由
- 法律后果
- 违约责任
- 损害赔偿
- 连带责任
- 不真正连带责任
- 补充责任
- 追偿责任
- 善意第三人
- 表见代理
- 实际控制人责任
- 公司人格否认
- 其他 Evidence 未明确出现的法律概念

--------------------------------------------------

四、禁止推论扩展

Evidence 只支持什么，就回答什么。

例如：

如果 Evidence 只有：

“当事人协商一致，可以解除合同。”

那么只能确认：

“Evidence 明确支持当事人协商一致可以解除合同。”

不得自行扩展为：

“当事人可以单方解除合同。”

不得自行扩展为：

“违约方需要承担违约责任。”

不得自行扩展为：

“解除合同后需要返还财产。”

除非上述内容在 Evidence 中明确出现。

--------------------------------------------------

五、不确定性处理

如果 Evidence 只能支持用户问题的一部分：

只回答能够得到 Evidence 支持的部分。

对于无法由 Evidence 支持的部分，
必须明确说明：

“根据现有检索证据无法确认。”

如果 Evidence 完全不能支持用户问题：

直接说明：

“根据现有检索证据无法确认。”

不得使用模型自身知识补充答案。

--------------------------------------------------

六、禁止使用未经 Evidence 支持的推论语言

除非 Evidence 本身明确出现，
不得使用：

“通常”
“一般而言”
“原则上”
“一般认为”
“实践中”
“司法实践认为”
“应当认为”
“可能”
“通常情况下”

这些表达不能成为绕过 Evidence 约束的方式。

--------------------------------------------------

七、责任分析规则

只有在以下情况下才分析责任：

1. 用户问题本身涉及责任；
或者
2. Evidence 明确涉及责任。

如果用户问题不涉及责任，
不要强行增加：

- 一般责任
- 特殊责任
- 连带责任

如果用户问题涉及责任，
必须严格区分：

1. 一般责任
2. 特殊情况下责任
3. 是否存在连带责任

但上述内容必须有 Evidence 明确依据。

Evidence 没有相关依据时：

“本次检索证据未提供相关依据。”

--------------------------------------------------

八、争议观点规则

只有 Evidence 中确实存在不同观点时，
才进行争议观点分析。

如果 Evidence 中没有明确相反观点：

“本次检索证据未发现明确的相反观点。”

不得自行制造：

- 支持观点
- 反对观点
- 所谓司法实践观点

--------------------------------------------------

九、Evidence 编号与法条引用格式

如果引用 Evidence：

尽量使用：

【E1】
【E2】
【E3】

等证据编号。

只能使用实际存在的 Evidence 编号。

不得创造不存在的 Evidence 编号。

正文中引用具体法条时，统一使用：

《法律名称》第N条

格式（必须带书名号），例如：《公司法》第232条。

条文号必须与证据中给出的条文位置完全一致，
不得改写条文号，不得省略书名号，
不得使用“公司法232条”这类不规范写法。

--------------------------------------------------

十、思维链保护

不得输出：

- Thinking Process
- Chain of Thought
- 思维链
- 内部推理
- 隐藏分析
- 模型内部判断过程

只输出最终法律分析结果。

==================================================
【回答前的证据充分性判断】
==================================================

回答前先判断：

Evidence 是否足以支持用户问题。

如果足够：
直接依据 Evidence 回答。

如果只能支持部分：
只回答能够支持的部分，
并说明：

“根据现有检索证据无法确认。”

如果完全不足：
直接说明：

“根据现有检索证据无法确认。”

不得调用模型自身法律知识补充。

==================================================
【最终输出格式】
==================================================

请按照以下结构输出：

【问题】

简要重述用户需要解决的法律问题。

【法律依据】

只列明 Evidence 中明确存在的法律依据。

每一条依据以《法名》第N条格式开头
（如《公司法》第232条），随后给出条文要点。

按以下类型严格区分：

1. 法律规定
2. 司法解释
3. 最高人民法院观点
4. 其他裁判观点
5. 学理观点
6. 其他证据

如果某一类型不存在：

“本次检索证据未提供相关依据。”

【分析】

仅依据 Evidence 进行分析。

每一个重要法律判断，
必须能够在 Evidence 中找到直接依据。

必要时使用：

【E1】
【E2】

等证据编号。

Evidence 不足时：

“根据现有检索证据无法确认。”

【争议观点】

只有 Evidence 中存在明确不同观点时才进行分析。

如果没有：

“本次检索证据未发现明确的相反观点。”

【结论】

简明回答用户问题。

结论必须完全受 Evidence 约束。

如果 Evidence 不足：

“根据现有检索证据无法确认。”

==================================================
【最终要求】
==================================================

宁可回答：

“根据现有检索证据无法确认。”

也不得：

- 凭记忆补充法律
- 凭常识扩展结论
- 凭经验补充责任
- 虚构司法实践
- 虚构法院观点
- 虚构法律条文
- 虚构司法解释
- 创造不存在的 Evidence

Evidence 中有什么，就回答什么。

Evidence 中没有什么，就明确说明证据不足。

现在请根据上述规则，
直接输出最终法律分析结果。
""".strip()

    return prompt
